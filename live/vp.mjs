import crypto from 'node:crypto';
import { VerificationRequestV1, VerifiablePresentationV1, VerificationAuditRecordV1, ConcordiumHdWallet } from '@concordium/web-sdk/wasm';
import { IdentityProviderDID, createAccountCommitmentInputWithHdWallet, CredentialRegistrationId } from '@concordium/web-sdk';
import { testnetClient } from './src/net.mjs';
import { readSecret } from './src/secrets.mjs';
import { loadAccounts, address, roleSigner } from './src/signers.mjs';
const grpc = testnetClient();
const acc = loadAccounts();
const id = readSecret('identity-owner');
const ctx = VerificationRequestV1.createSimpleContext(crypto.randomBytes(32), 'trustrail-test', 'trustrail:test:auth:0', 'approve payment');
const claims = VerificationRequestV1.claimsBuilder().addAccountClaims([new IdentityProviderDID('Testnet', 0)], (b) => b.addMinimumAge(18)).getClaims();
console.log(JSON.stringify(ctx).slice(0,300));
const req = await VerificationRequestV1.createAndAnchor(grpc, { sender: address(acc.cosigner), signer: roleSigner(acc.cosigner) }, ctx, claims);
console.log('request anchored', req.transactionRef.toString?.() ?? JSON.stringify(req.transactionRef));
await grpc.waitForTransactionFinalization(req.transactionRef);
const ownerInfo = await grpc.getAccountInfo(address(acc.owner));
const cred = ownerInfo.accountCredentials[0].value.contents;
const credId = cred.credId ?? cred.regId;
console.log('credId', credId?.slice(0,16));
const wallet = ConcordiumHdWallet.fromHex(id.seedAsHex, 'Testnet');
const { AccountClaims } = {};
const stmts = VerifiablePresentationV1.noRevealRequestedStatements(claims[0].statements);
const subj = VerifiablePresentationV1.createAccountClaims('Testnet', CredentialRegistrationId.fromHexString(credId), 0, stmts);
console.log(JSON.stringify(subj).slice(0,300));

const input = createAccountCommitmentInputWithHdWallet(stmts, 0, id.idObject.attributeList, wallet, 0, acc.owner.credNumber);
const pres = await VerifiablePresentationV1.createFromAnchor(grpc, req, [subj], [input], []);
console.log('presentation bytes', JSON.stringify(pres.toJSON()).length);
const v = await VerifiablePresentationV1.verifyWithNode(pres, grpc, 'Testnet');
console.log('verify', v.type, v.type==='failed'? v.error.message : JSON.stringify(v.result.credentialsStatus));
const ar = await VerificationAuditRecordV1.createAndAnchor('trustrail-test-1', req, pres, grpc, { metadata: { sender: address(acc.cosigner), signer: roleSigner(acc.cosigner) }, info: { authId: 0 } }, { network: 'Testnet' });
console.log('audit', ar.type, ar.type==='failed'? ar.error.message : ar.result.anchorTransactionRef.toString?.());
